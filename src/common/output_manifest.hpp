#pragma once

#include <filesystem>
#include <functional>
#include <ostream>
#include <string>
#include <vector>

namespace vcxproj {

// Generation manifest: every generation records the files it wrote, and stores the list in
// <directory>/.sighmake-manifest under a section named after the generator and the target OS.
// On the next generation with the same generator and target OS, files in the previous list that
// were not written again (removed or renamed projects, projects that no longer apply to the target)
// are deleted. Files that are in no manifest are never deleted unless prune_unlisted is set.

inline constexpr const char* kOutputManifestFilename = ".sighmake-manifest";

// Records a file written by the running generation (absolute or relative to the working directory).
void record_generated_output(const std::filesystem::path& path);
// Forgets every recorded file; call before a generation starts.
void reset_generated_outputs();
// Files recorded since the last reset, absolute and normalized, in recording order without duplicates.
std::vector<std::filesystem::path> generated_outputs();

struct OutputManifestScope {
    // Directory holding the manifest. Only files below it are listed in the manifest or removed.
    std::filesystem::path directory;
    // Section name: "<generator> <target-os>", e.g. "makefile linux".
    std::string key;
    // Directory depth searched for probable outputs that are in no manifest (0 = the directory itself).
    int probable_search_depth = 0;
    // True when a file in no manifest looks like an output of this generator (name pattern and,
    // for text outputs, the sighmake header). Path is relative to `directory`, '/'-separated.
    std::function<bool(const std::filesystem::path& absolute, const std::string& relative)> probable_output;
};

struct StaleOutputOptions {
    bool keep_stale = false;      // --keep-stale: list stale outputs, delete nothing
    bool prune_unlisted = false;  // --prune-unlisted: also delete probable outputs in no manifest
};

struct StaleOutputReport {
    bool had_previous_manifest = false;
    std::vector<std::string> removed;           // stale manifest entries deleted
    std::vector<std::string> kept;              // stale manifest entries kept (--keep-stale)
    std::vector<std::string> unlisted;          // probable stale outputs in no manifest, listed only
    std::vector<std::string> unlisted_removed;  // probable stale outputs deleted (--prune-unlisted)
    std::vector<std::string> modified;          // stale manifest entries kept: no longer what sighmake wrote
    std::vector<std::string> failed;            // deletions that failed
    bool manifest_written = false;
};

// Compares the outputs of this generation with the previous manifest, removes or lists the stale
// ones, writes the new manifest and prints a summary to `out` (warnings to `err`).
StaleOutputReport reconcile_generated_outputs(const OutputManifestScope& scope,
                                              const std::vector<std::filesystem::path>& produced,
                                              const StaleOutputOptions& options,
                                              std::ostream& out, std::ostream& err);

// Lowercase name of the effective target OS ("windows", "linux", "macos", "ios", "android").
std::string target_os_manifest_name();

// True when the first bytes of the file contain the "# Generated by sighmake" header.
bool has_sighmake_header(const std::filesystem::path& file);

} // namespace vcxproj
